"""A language-model extractor, constrained to the extraction schema.

Optional in every sense. It needs an API key and a network, so it is excluded
from the test suite, from CI, and from the committed leaderboard — everything
this repository verifies runs without it. Install with `pip install -e ".[llm]"`.

On structured output and citations
----------------------------------
The Claude API offers two mechanisms that both look like the right tool here,
and **they cannot be combined in one request**: sending `citations: {enabled:
true}` on a document block together with `output_config.format` returns a 400.
That is not a limitation to work around, it is a design choice to make, and it
is worth stating which one this repository made and why.

We use the JSON schema, and verify quotations ourselves.

Citations would give us character offsets computed by the API — a stronger
guarantee about the span than a model-supplied string. But it would be a
guarantee available *only to this extractor*. The rule-based baselines cannot
produce API citations, a submission built on another vendor's model cannot
either, and a benchmark whose grounding guarantee is stronger for one class of
entrant is not measuring the same thing across the leaderboard.

Verifying quotations in `synthesis.base.ground` gives every extractor the same
check, enforced by us rather than self-reported. The cost is that we cannot
distinguish a quotation the model copied from one it reconstructed correctly
from memory — both appear in the text and both pass. For this benchmark that
distinction does not matter: a reconstruction that is character-for-character
identical to the source *is* a correct quotation.

`--citations` runs the other configuration for comparison — citations enabled,
no schema, output parsed from prose. It is provided because "the two mechanisms
disagree" would be a genuinely interesting finding, and because a claim like the
one above should be checkable rather than merely asserted.

Never prefill
-------------
Prefilling the assistant turn to force a JSON opening brace is the old way to do
this, and it now returns a 400 on current models. `output_config.format` is the
replacement and is what this module uses.
"""

from __future__ import annotations

import json
import os
from collections.abc import Sequence

from .base import Claim, Document
from .schema import extraction_schema, field_guidance

#: Default model. Extraction rewards care over speed — a wrong value that is
#: correctly quoted is the expensive failure here, because it looks right.
DEFAULT_MODEL = "claude-opus-5"

#: The output is a handful of short JSON objects, so this is generous. The
#: *input* is a full article, which is where the tokens actually go.
MAX_TOKENS = 8_000

SYSTEM_PROMPT = """\
You extract study characteristics from published clinical trial reports for a \
systematic reviewer. You are reading one article and reporting what it says \
about how it was conducted.

Two rules matter more than completeness.

First: every value you report must be accompanied by a quotation copied verbatim \
from the article — character for character, including its original casing and \
punctuation. Do not paraphrase, do not tidy, do not reconstruct a sentence from \
memory. A quotation that does not appear in the article is discarded along with \
the value attached to it, so a fabricated quotation is strictly worse than no \
claim at all.

Second: report only what this article states about this trial. Clinical papers \
discuss other people's trials at length, especially in the introduction and \
discussion. A participant count from a cited study is a real number, correctly \
quoted, and the wrong answer.

If the article does not report a field, omit it. Omission is the correct answer \
for an unreported field and is scored as such. A plausible guess is not.

Fields:
{fields}
"""


class LLMExtractor:
    """Schema-constrained extraction through the Claude API.

    Not deterministic, and the leaderboard says so: the committed results file
    is regenerated by CI from the deterministic baselines only, and an entry
    from this extractor is recorded with the model id and marked
    `deterministic: false` so nobody mistakes a re-run for a reproduction.
    """

    name = "llm"

    def __init__(
        self,
        model: str = DEFAULT_MODEL,
        *,
        effort: str = "medium",
        use_citations: bool = False,
        api_key: str | None = None,
    ) -> None:
        try:
            import anthropic
        except ImportError as exc:  # pragma: no cover - exercised only without the extra
            raise ImportError(
                "The LLM extractor needs the anthropic package. "
                'Install it with: pip install -e ".[llm]"'
            ) from exc

        key = api_key or os.environ.get("ANTHROPIC_API_KEY")
        if not key:
            raise RuntimeError(
                "No ANTHROPIC_API_KEY. Everything CI checks — the tests, the "
                "deterministic baselines, the published leaderboard — runs without "
                "one; only this extractor needs it."
            )

        self.model = model
        self.effort = effort
        self.use_citations = use_citations
        self._client = anthropic.Anthropic(api_key=key)

    def extract(self, document: Document) -> Sequence[Claim]:
        if self.use_citations:
            return self._extract_with_citations(document)
        return self._extract_with_schema(document)

    def _extract_with_schema(self, document: Document) -> list[Claim]:
        response = self._client.messages.create(
            model=self.model,
            max_tokens=MAX_TOKENS,
            system=SYSTEM_PROMPT.format(fields=field_guidance()),
            output_config={
                "format": {"type": "json_schema", "schema": extraction_schema()},
                "effort": self.effort,
            },
            messages=[
                {
                    "role": "user",
                    "content": (
                        f"Article title: {document.title}\n"
                        f"Journal: {document.journal}\n\n"
                        f"{document.text}"
                    ),
                }
            ],
        )

        # A refusal returns HTTP 200 with an empty or partial content list, so
        # reading content[0] unconditionally would raise IndexError and look
        # like a parsing bug. Surface it as what it is.
        if response.stop_reason == "refusal":
            raise RuntimeError(
                f"The model declined to process {document.document_id}. "
                "This is a content-policy outcome, not an extraction failure."
            )

        text = next((b.text for b in response.content if b.type == "text"), "")
        if not text:
            return []
        return _parse_claims(json.loads(text))

    def _extract_with_citations(self, document: Document) -> list[Claim]:
        """The alternative configuration: API citations, no schema.

        Kept deliberately separate rather than folded into the main path with a
        flag, because the two produce different failure modes and mixing them
        would make a disagreement between them impossible to attribute.

        The document is sent as a `document` content block with citations
        enabled, so the response arrives as several text blocks, the cited ones
        carrying a `citations` array whose `cited_text` is the exact span the
        API resolved. That span is what becomes the claim's quotation — it comes
        from the API's own resolution rather than from the model's output, which
        is the entire point of running this comparison.
        """
        response = self._client.messages.create(
            model=self.model,
            max_tokens=MAX_TOKENS,
            system=SYSTEM_PROMPT.format(fields=field_guidance()),
            messages=[
                {
                    "role": "user",
                    "content": [
                        {
                            "type": "document",
                            "source": {
                                "type": "text",
                                "media_type": "text/plain",
                                "data": document.text,
                            },
                            "title": document.title,
                            "citations": {"enabled": True},
                        },
                        {
                            "type": "text",
                            "text": (
                                "Report each field on its own line as "
                                "`field: value`, citing the sentence you took it "
                                "from. Omit fields the article does not report."
                            ),
                        },
                    ],
                }
            ],
        )

        if response.stop_reason == "refusal":
            raise RuntimeError(f"The model declined to process {document.document_id}.")

        claims: list[Claim] = []
        for block in response.content:
            if block.type != "text":
                continue
            citations = getattr(block, "citations", None) or []
            if not citations:
                continue
            parsed = _parse_line(block.text)
            if parsed is None:
                continue
            field, value = parsed
            claims.append(
                Claim(
                    field=field,
                    value=value,
                    # The API's resolved span, not the model's rendering of it.
                    quote=citations[0].cited_text,
                    section="cited",
                )
            )
        return claims

    def describe(self) -> dict:
        return {
            "extractor": "LLMExtractor",
            "approach": "citations, no schema" if self.use_citations else "json schema",
            "model": self.model,
            "effort": self.effort,
            "deterministic": False,
            "requires_network": True,
            "can_hallucinate": True,
        }


def _parse_claims(payload: dict) -> list[Claim]:
    """Turn the schema-constrained JSON into claims.

    Tolerant of a missing `claims` key even though the schema requires it: a
    constrained decode that hit the token ceiling can return valid-looking JSON
    that is missing the array, and returning nothing is a better failure than a
    KeyError halfway through a benchmark run over thirty documents.
    """
    return [
        Claim(
            field=str(item.get("field", "")),
            value=str(item.get("value", "")),
            quote=str(item.get("quote", "")),
            section=str(item.get("section", "") or ""),
        )
        for item in payload.get("claims", [])
    ]


def _parse_line(text: str) -> tuple[str, str] | None:
    """Pull `field: value` out of a prose line, for the citations path only."""
    line = text.strip().splitlines()[0] if text.strip() else ""
    if ":" not in line:
        return None
    field, _, value = line.partition(":")
    field, value = field.strip().strip("`*- "), value.strip()
    return (field, value) if field and value else None
